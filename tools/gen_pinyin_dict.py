#!/usr/bin/env python3
"""
Generate the Pinyin candidate dictionary consumed by lv_ime_pinyin.

The pinyin engine itself is the open-source IME shipped with LVGL
(`lvgl/src/others/ime/lv_ime_pinyin.c`, MIT). Its built-in dictionary only has
322 syllables and a few hundred characters, which is far too little for a
usable chat input. This script turns the Unicode Han Database (Unihan, released
by the Unicode Consortium under the Unicode License) into a full dictionary:

  * every GB 2312 level-1 + level-2 hanzi (6763 characters, the ones a Chinese
    user types day to day) for the URO block U+4E00..U+9FFF;
  * pinyin taken from `kMandarin`, tones stripped, `ü` mapped to `v`
    (the same convention LVGL's example dictionary uses, e.g. "nv");

The output is `assets/ime/pinyin_dict.txt`, one `pinyin<TAB>characters` line
per syllable. It is loaded at run time by board_app/app/chat/ui/chat_ui.c and
passed to `lv_ime_pinyin_set_dict()`; the file can be edited without rebuilding.

Usage:
  python3 tools/gen_pinyin_dict.py --unihan /tmp/Unihan.zip \
      --output assets/ime/pinyin_dict.txt

See board_app/docs/11-chat-and-ime.md for the full attribution.

SPDX-License-Identifier: MIT
Copyright (c) 2026 Board App contributors
"""
import argparse
import os
import re
import sys
import unicodedata
import zipfile

# Level-1 (常用字) first so that the most common characters lead each
# candidate list; level-2 (次常用字) follows.
GB2312_LEVEL1 = (0xB0, 0xD7)   # 区 16-55
GB2312_LEVEL2 = (0xD8, 0xF7)   # 区 56-87


def strip_tone(syllable: str) -> str:
    """'yī' -> 'yi', 'lǜ' -> 'lv', 'ê' -> 'e'."""
    out = []
    for ch in unicodedata.normalize("NFD", syllable):
        if unicodedata.combining(ch):
            continue
        if ch in ("ü", "ǖ", "ǘ", "ǚ", "ǜ"):
            out.append("v")
            continue
        out.append(ch)
    text = "".join(out).lower()
    text = text.replace("ü", "v").replace("ê", "e")
    return text


def gb2312_hanzi() -> list:
    chars = []
    for first, last in (GB2312_LEVEL1, GB2312_LEVEL2):
        for hi in range(first, last + 1):
            for lo in range(0xA1, 0xFF):
                if hi == 0xD7 and lo > 0xF9:  # level-1 ends at 0xD7F9
                    continue
                try:
                    ch = bytes([hi, lo]).decode("gb2312")
                except UnicodeDecodeError:
                    continue
                if "\u4e00" <= ch <= "\u9fff":
                    chars.append(ch)
    return chars


def load_mandarin(zip_path: str) -> dict:
    readings = {}
    with zipfile.ZipFile(zip_path) as zf:
        text = zf.read("Unihan_Readings.txt").decode("utf-8")
    for line in text.splitlines():
        if line.startswith("#") or "\tkMandarin\t" not in line:
            continue
        code, _, value = line.split("\t")
        readings[int(code[2:], 16)] = value.strip()
    return readings


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--unihan", required=True, help="Unihan.zip (unicode.org)")
    parser.add_argument("--output", required=True, help="output pinyin_dict.txt")
    args = parser.parse_args()

    if not os.path.isfile(args.unihan):
        print("Unihan.zip not found:", args.unihan, file=sys.stderr)
        print("Download: https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip",
              file=sys.stderr)
        return 1

    mandarin = load_mandarin(args.unihan)
    hanzi = gb2312_hanzi()

    table = {}
    skipped = 0
    for ch in hanzi:
        raw = mandarin.get(ord(ch))
        if not raw:
            skipped += 1
            continue
        # kMandarin may list several readings ("jiǔ guǐ"); the first one is
        # the most common pronunciation.
        pinyin = strip_tone(raw.split()[0])
        if not re.fullmatch(r"[a-z]+", pinyin):
            skipped += 1
            continue
        table.setdefault(pinyin, []).append(ch)

    if not table:
        print("no pinyin entries produced", file=sys.stderr)
        return 1

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Pinyin candidate dictionary for LVGL lv_ime_pinyin.\n")
        f.write("# Generated by board_app/tools/gen_pinyin_dict.py from\n")
        f.write("# Unihan (Unicode License v3, https://www.unicode.org/license.txt)\n")
        f.write("# restricted to the GB 2312 hanzi set. Format: pinyin<TAB>chars\n")
        for pinyin in sorted(table):
            f.write("%s\t%s\n" % (pinyin, "".join(table[pinyin])))

    total = sum(len(v) for v in table.values())
    print("syllables: %d  characters: %d  skipped: %d  -> %s"
          % (len(table), total, skipped, args.output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
